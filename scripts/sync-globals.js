// Regenerates the globals table in roblox/Sandbox.luau from luau-lsp's Roblox
// definitions, so a global Roblox adds later is wrapped instead of leaking real
// Instances. Run before deploying; `--check` exits 1 if the table is stale.

const fs = require("fs");
const path = require("path");

const SOURCE =
  "https://raw.githubusercontent.com/JohnnyMorganz/luau-lsp/main/scripts/globalTypes.d.luau";
const SANDBOX = path.join(__dirname, "..", "roblox", "Sandbox.luau");
const BEGIN = "--[[GLOBALS]]";
const END = "--[[/GLOBALS]]";

// Luau builtins; luau-lsp's Roblox file only declares the Roblox additions.
const STDLIB = [
  "assert", "bit32", "buffer", "collectgarbage", "coroutine", "debug", "error",
  "gcinfo", "getfenv", "getmetatable", "ipairs", "loadstring", "math", "newproxy",
  "next", "os", "pairs", "pcall", "print", "rawequal", "rawget", "rawlen", "rawset",
  "require", "select", "setfenv", "setmetatable", "string", "table", "tonumber",
  "tostring", "type", "typeof", "unpack", "utf8", "vector", "xpcall", "_G", "_VERSION",
];

// Overridden explicitly in Sandbox.luau or LuauBot.
const HANDLED = new Set([
  "game", "Game", "workspace", "Workspace", "script", "shared", "Instance",
  "typeof", "require", "stats", "Stats", "settings", "UserSettings", "PluginManager",
  "print", "warn", "loadstring", "task", "spawn", "delay", "_G", "coroutine",
  "RaycastParams", "OverlapParams",
]);

// Cannot produce or consume Instances, so they pass through untouched.
const PURE = new Set([
  ...STDLIB.filter((name) => !HANDLED.has(name)),
  "Axes", "BrickColor", "CFrame", "CatalogSearchParams", "Color3", "ColorSequence",
  "ColorSequenceKeypoint", "Content", "DateTime", "DockWidgetPluginGuiInfo", "Enum",
  "Faces", "FloatCurveKey", "Font", "NumberRange", "NumberSequence",
  "NumberSequenceKeypoint", "Path2DControlPoint", "PathWaypoint", "PhysicalProperties",
  "Random", "Ray", "Rect", "Region3", "Region3int16", "RotationCurveKey",
  "SecurityCapabilities", "SharedTable", "TweenInfo", "UDim", "UDim2", "ValueCurveKey",
  "Vector2", "Vector2int16", "Vector3", "Vector3int16", "Delay", "Wait", "wait",
  "ElapsedTime", "elapsedTime", "Version", "version", "tick", "time", "printidentity",
  "Secret", "plugin", "DebuggerManager",
]);

// Known to take or return Instances without a dedicated wrapper yet.
const WRAP = new Set(["InstanceHandle", "User"]);

function parseDeclared(source) {
  const names = new Set();
  for (const match of source.matchAll(/^declare (?:function )?([A-Za-z_][A-Za-z0-9_]*)/gm)) {
    if (match[1] !== "class" && match[1] !== "extern") names.add(match[1]);
  }
  return names;
}

function classify(names) {
  const entries = [...names].sort().map((name) => {
    if (HANDLED.has(name)) return [name, "handled"];
    if (PURE.has(name)) return [name, "pure"];
    if (WRAP.has(name)) return [name, "wrap"];
    return [name, "auto"];
  });
  return entries;
}

function render(entries) {
  const lines = [BEGIN, "-- generated by scripts/sync-globals.js; do not edit by hand", "local GLOBALS = {"];
  for (const [name, kind] of entries) lines.push(`\t${name} = "${kind}",`);
  lines.push("}");
  // Static reads, since the global table can't be enumerated and getfenv would deopt.
  lines.push("local GLOBAL_VALUES = {");
  for (const [name, kind] of entries) {
    if (kind === "wrap" || kind === "auto") lines.push(`\t${name} = ${name},`);
  }
  lines.push("}");
  lines.push(END);
  return lines.join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch ${SOURCE}: ${res.status}`);
  const names = parseDeclared(await res.text());
  for (const name of STDLIB) names.add(name);
  for (const name of HANDLED) names.add(name);

  const entries = classify(names);
  const block = render(entries);
  const sandbox = fs.readFileSync(SANDBOX, "utf8");
  const start = sandbox.indexOf(BEGIN);
  const end = sandbox.indexOf(END);
  if (start === -1 || end === -1) throw new Error(`${SANDBOX} has no ${BEGIN} block`);
  const current = sandbox.slice(start, end + END.length).replace(/\r\n/g, "\n");

  const unclassified = entries.filter(([, kind]) => kind === "auto").map(([name]) => name);
  if (check) {
    if (current !== block) {
      console.error("Sandbox globals are out of date; run node scripts/sync-globals.js");
      if (unclassified.length) console.error(`Unclassified: ${unclassified.join(", ")}`);
      process.exit(1);
    }
    console.log(`Sandbox globals up to date (${entries.length} names)`);
    return;
  }
  fs.writeFileSync(SANDBOX, sandbox.slice(0, start) + block + sandbox.slice(end + END.length));
  console.log(`Wrote ${entries.length} globals${unclassified.length ? `; auto-wrapped: ${unclassified.join(", ")}` : ""}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
